// Agents that do not read `.agents/skills` and need their own project-level copy.
const targetDirs = [join(rootDir, '.claude', 'skills')]

const checkOnly = process.argv.includes('--check')

async function readLockedSkillNames() {
  const lock = JSON.parse(await readFile(lockFile, 'utf8'))
  if (lock?.skills === null || typeof lock?.skills !== 'object') {
    throw new Error(`Unexpected format of ${relative(rootDir, lockFile)}`)
  }
  return Object.keys(lock.skills)
}

async function readSourceSkillNames() {
  const entries = await readdir(sourceDir, { withFileTypes: true })
  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
}

async function hashDirectory(dir) {
  const hash = createHash('sha256')
  let entries
  try {
    entries = await readdir(dir, { recursive: true, withFileTypes: true })
  } catch (error) {
    if (error.code === 'ENOENT') return null
    throw error
  }
  const files = entries
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name))
    .sort()
  for (const file of files) {
    hash.update(relative(dir, file).replaceAll('\\', '/'))
    hash.update(await readFile(file))
  }
  return hash.digest('hex')
}

