// A replacement whose source and result are both missing no longer matches the skill,
// usually because an upstream update reworded the passage.
const staleAdaptations = []

async function adaptThirdPartySkills() {
  const changed = []
  for (const { file, replacements } of skillAdaptations) {
    const path = join(sourceDir, file)
    let content
    try {
      content = await readFile(path, 'utf8')
    } catch (error) {
      if (error.code === 'ENOENT') continue
      throw error
    }
    // Replacements span lines; Git stores these files with LF (.gitattributes) anyway.
    let adapted = content.replaceAll('\r\n', '\n')
    for (const [from, to] of replacements) {
      if (!adapted.includes(from) && !adapted.includes(to)) {
        staleAdaptations.push(`${relative(rootDir, path)}: ${from.split('\n')[0]}`)
      }
      adapted = adapted.replaceAll(from, to)
    }
    if (adapted === content) continue
    changed.push(relative(rootDir, path))
    if (!checkOnly) await writeFile(path, adapted)
  }
  return changed
}

// References to skills, files and commands this repository does not have. A match means
// an upstream skill update brought text that the adaptations above do not cover yet.
const missingTargets = [
  { pattern: /superpowers:[\w-]+/g, reason: 'superpowers sub-skills are not installed' },
  {
    pattern: /CONTEXT\.md/g,
    reason: 'the domain vocabulary lives in PROJECT_OVERVIEW.md',
  },
  { pattern: /docs\/agents\/issue-tracker\.md/g, reason: 'tasks live in Backlog.md' },
  { pattern: /docs\/superpowers\//g, reason: 'plans live in Backlog.md tasks' },
  {
    pattern: /\/setup-matt-pocock-skills/g,
    reason: 'no such command in this repository',
  },
]
const skillReferencePatterns = [
  /Skill tool with "([\w-]+)"/g,
  /the `([\w-]+)` skill/g,
  // Unquoted names only when hyphenated, so prose like "the generated skill" is not a match.
  /the ([a-z]+-[\w-]+) skill\b/g,
]

async function findBrokenReferences(skillNames) {
  const problems = []
  const entries = await readdir(sourceDir, { recursive: true, withFileTypes: true })
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.md')) continue
    const path = join(entry.parentPath, entry.name)
    const content = await readFile(path, 'utf8')
    const where = relative(rootDir, path)
    for (const { pattern, reason } of missingTargets) {
      for (const match of content.matchAll(pattern)) {
        problems.push(`${where}: ${match[0]} (${reason})`)
      }
    }
    for (const pattern of skillReferencePatterns) {
      for (const match of content.matchAll(pattern)) {
        const name = match[1]
        if (name && !skillNames.includes(name)) {
          problems.push(`${where}: references missing skill "${name}"`)
        }
      }
    }
  }
  return problems
}

const unadaptedSkillFiles = await adaptThirdPartySkills()

const skillNames = await readSourceSkillNames()
const missingLockedSkills = (await readLockedSkillNames()).filter(
  (name) => !skillNames.includes(name),
)
if (missingLockedSkills.length > 0) {
  throw new Error(
    `Skills listed in skills-lock.json are missing in .agents/skills: ${missingLockedSkills.join(', ')}`,
  )
}

if (staleAdaptations.length > 0) {
  console.error(
    `Skill adaptations match neither the original nor the adapted text:\n  ${staleAdaptations.join('\n  ')}`,
  )
  console.error(
    'Update the passage in skillAdaptations in scripts/sync-agent-skills.mjs.',
  )
  process.exitCode = 1
}

const brokenReferences = await findBrokenReferences(skillNames)
if (brokenReferences.length > 0) {
  console.error(
    `Agent skills reference skills, files or commands this repository does not have:\n  ${brokenReferences.join('\n  ')}`,
  )
  console.error('Adapt the passage in skillAdaptations in scripts/sync-agent-skills.mjs.')
  process.exitCode = 1
}

const outOfSync = []

for (const targetDir of targetDirs) {
  for (const name of skillNames) {
    const source = join(sourceDir, name)
    const target = join(targetDir, name)
    const sourceHash = await hashDirectory(source)
    if (sourceHash === (await hashDirectory(target))) continue

    outOfSync.push(relative(rootDir, target))
    if (checkOnly) continue

    await rm(target, { recursive: true, force: true })
    await mkdir(targetDir, { recursive: true })
    await cp(source, target, { recursive: true, dereference: true })
  }
}

if (unadaptedSkillFiles.length > 0) {
  if (checkOnly) {
    console.error(
      `Third-party skills are not adapted to this repository:\n  ${unadaptedSkillFiles.join('\n  ')}`,
    )
    process.exitCode = 1
  } else {
    console.log(`Adapted third-party skills:\n  ${unadaptedSkillFiles.join('\n  ')}`)
  }
}

if (outOfSync.length === 0) {
  console.log(`Agent skills are in sync (${skillNames.length} skills).`)
} else if (checkOnly) {
  console.error(`Agent skills are out of sync:\n  ${outOfSync.join('\n  ')}`)
  console.error('Run: node scripts/sync-agent-skills.mjs')
  process.exitCode = 1
} else {
  console.log(`Synced agent skills:\n  ${outOfSync.join('\n  ')}`)
}
